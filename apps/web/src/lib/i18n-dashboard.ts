const Ctx = createContext<{ lang: DashLang; t: (k: DashKey) => string; st: (status: string) => string; setLang: (l: DashLang) => void }>({
  lang: 'ru',
  t: (k) => ru[k],
  st: (s) => STATUS.ru[s] ?? s,
  setLang: () => undefined,
});

export function DashI18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<DashLang>('ru');
  useEffect(() => {
    const saved = localStorage.getItem('bk_dash_lang');
    if (saved === 'kk' || saved === 'ru') setLangState(saved);
  }, []);
  const setLang = useCallback((l: DashLang) => {
    localStorage.setItem('bk_dash_lang', l);
    setLangState(l);
  }, []);
  const t = useCallback((k: DashKey) => DICTS[lang][k] ?? ru[k], [lang]);
  const st = useCallback((s: string) => STATUS[lang][s] ?? STATUS.ru[s] ?? s, [lang]);
  return createElement(Ctx.Provider, { value: { lang, t, st, setLang } }, children);
}

export function useT() {
  return useContext(Ctx);
}
