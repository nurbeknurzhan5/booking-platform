const DICTS: Record<Lang, Dict> = { ru, kk, en };
export type PublicKey = keyof Dict;

export function pt(lang: string, key: PublicKey): string {
  return (DICTS[(lang as Lang) in DICTS ? (lang as Lang) : 'ru'] ?? ru)[key];
}

export function isLang(l: string): l is Lang {
  return l === 'ru' || l === 'kk' || l === 'en';
}
